-- Refunds (SRS 4.9): orders and tickets can be REFUNDED, refunds are recorded, events have a refund policy.

-- Hibernate's CHECK constraints list the allowed enum values, so they are widened for the new status.
ALTER TABLE tickets DROP CONSTRAINT IF EXISTS tickets_status_check;
ALTER TABLE tickets ADD CONSTRAINT tickets_status_check
    CHECK (status IN ('VALID', 'USED', 'CANCELLED', 'REFUNDED'));

ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_status_check;
ALTER TABLE orders ADD CONSTRAINT orders_status_check
    CHECK (status IN ('PENDING', 'PAID', 'CANCELLED', 'EXPIRED', 'REFUNDED'));

ALTER TABLE events ADD COLUMN refund_policy character varying(2000);

CREATE TABLE refunds (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    order_id bigint NOT NULL,
    payment_id bigint,
    reference character varying(80) NOT NULL,
    status character varying(20) NOT NULL,
    amount numeric(12,2) NOT NULL,
    provider character varying(20) NOT NULL,
    simulated boolean NOT NULL,
    reason character varying(500),
    failure_reason character varying(500),
    initiated_by_id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    completed_at timestamp(6) without time zone,
    CONSTRAINT refunds_pkey PRIMARY KEY (id),
    CONSTRAINT uk_refunds_reference UNIQUE (reference),
    CONSTRAINT refunds_status_check CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT refunds_amount_check CHECK (amount > 0),
    CONSTRAINT fk_refunds_order FOREIGN KEY (order_id) REFERENCES orders(id),
    CONSTRAINT fk_refunds_payment FOREIGN KEY (payment_id) REFERENCES payments(id),
    CONSTRAINT fk_refunds_initiated_by FOREIGN KEY (initiated_by_id) REFERENCES users(id)
);

CREATE INDEX idx_refunds_order ON refunds (order_id);

-- An order is refunded at most once: a second request can't start while one is open or after one succeeded.
CREATE UNIQUE INDEX uq_refunds_open_or_done_per_order ON refunds (order_id) WHERE status IN ('PENDING', 'SUCCEEDED');
