-- Simulated organizer payouts (SRS 3.2, 4.6, 4.10). One payout per finished event; no money ever moves.

CREATE TABLE payouts (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id bigint NOT NULL,
    organizer_id bigint NOT NULL,
    status character varying(20) NOT NULL,
    -- Why an ON_HOLD payout waits (every type but ADMIN clears by itself once its cause is gone), or why it was cancelled.
    hold_type character varying(30),
    status_reason character varying(500),
    -- Breakdown, recalculated from the sales figures when the payout is made.
    gross_revenue numeric(12,2) NOT NULL,
    discounts numeric(12,2) NOT NULL,
    refunds numeric(12,2) NOT NULL,
    processing_fees numeric(12,2) NOT NULL,
    amount numeric(12,2) NOT NULL,
    scheduled_for timestamp(6) without time zone NOT NULL,
    paid_at timestamp(6) without time zone,
    reference character varying(80),
    -- Destination at the time of payment: bank name and the last 4 IBAN characters only.
    bank_name character varying(255),
    iban_last4 character varying(4),
    simulated boolean NOT NULL DEFAULT true,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT payouts_pkey PRIMARY KEY (id),
    CONSTRAINT uq_payouts_event UNIQUE (event_id),
    CONSTRAINT uq_payouts_reference UNIQUE (reference),
    CONSTRAINT payouts_status_check CHECK (status IN ('SCHEDULED', 'ON_HOLD', 'PAID', 'CANCELLED')),
    CONSTRAINT payouts_hold_type_check
        CHECK (hold_type IN ('ADMIN', 'NO_PAYOUT_ACCOUNT', 'EVENT_SUSPENDED', 'ORGANIZER_SUSPENDED')),
    CONSTRAINT fk_payouts_event FOREIGN KEY (event_id) REFERENCES events(id),
    CONSTRAINT fk_payouts_organizer FOREIGN KEY (organizer_id) REFERENCES users(id)
);

CREATE INDEX idx_payouts_status_scheduled ON payouts (status, scheduled_for);
CREATE INDEX idx_payouts_organizer ON payouts (organizer_id, scheduled_for);
