-- Administration (SRS 4.12): user suspension, reported events and platform settings.

-- User suspension: a platform admin can block an account without deleting it.
-- Checked on every authenticated request, because the role and identity come from the JWT.
ALTER TABLE users ADD COLUMN is_suspended boolean NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN suspended_at timestamp(6) without time zone;
ALTER TABLE users ADD COLUMN suspension_reason character varying(500);

-- Reports of events by users, reviewed by platform admins.
CREATE TABLE event_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id bigint NOT NULL,
    reporter_id bigint NOT NULL,
    reason character varying(30) NOT NULL,
    message character varying(1000),
    status character varying(20) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    reviewed_by_id bigint,
    reviewed_at timestamp(6) without time zone,
    resolution_note character varying(500),
    CONSTRAINT event_reports_pkey PRIMARY KEY (id),
    CONSTRAINT event_reports_reason_check
        CHECK (reason IN ('FRAUD', 'MISLEADING', 'INAPPROPRIATE', 'SPAM', 'OTHER')),
    CONSTRAINT event_reports_status_check CHECK (status IN ('OPEN', 'DISMISSED', 'ACTIONED')),
    CONSTRAINT fk_event_reports_event FOREIGN KEY (event_id) REFERENCES events(id),
    CONSTRAINT fk_event_reports_reporter FOREIGN KEY (reporter_id) REFERENCES users(id),
    CONSTRAINT fk_event_reports_reviewed_by FOREIGN KEY (reviewed_by_id) REFERENCES users(id)
);

CREATE INDEX idx_event_reports_status ON event_reports (status, created_at);
-- One open report per user and event; they can report again once it has been reviewed.
CREATE UNIQUE INDEX uq_event_reports_open_per_reporter ON event_reports (event_id, reporter_id) WHERE status = 'OPEN';

-- Platform settings changed by admins at runtime. A single row; NULL means "use the value from the environment".
CREATE TABLE platform_settings (
    id bigint NOT NULL,
    activation_fee_kzt numeric(12,2),
    processing_fee_percent numeric(5,2),
    updated_at timestamp(6) without time zone,
    updated_by_id bigint,
    CONSTRAINT platform_settings_pkey PRIMARY KEY (id),
    CONSTRAINT platform_settings_single_row CHECK (id = 1),
    CONSTRAINT platform_settings_activation_fee_check CHECK (activation_fee_kzt >= 0),
    CONSTRAINT platform_settings_processing_fee_check CHECK (processing_fee_percent >= 0 AND processing_fee_percent <= 50),
    CONSTRAINT fk_platform_settings_updated_by FOREIGN KEY (updated_by_id) REFERENCES users(id)
);

