-- Assigned seating (SRS 4.3.1). Additive only: older app versions ignore every new column and table.

-- Key of a predefined layout (src/main/resources/seating/<key>.json). Null = no seat map: general admission only.
ALTER TABLE venues ADD COLUMN seating_layout character varying(50);

ALTER TABLE events ADD COLUMN seating_mode character varying(20) NOT NULL DEFAULT 'GENERAL_ADMISSION';
ALTER TABLE events ADD CONSTRAINT events_seating_mode_check
    CHECK (seating_mode IN ('GENERAL_ADMISSION', 'ASSIGNED'));

-- The event's own copy of its venue's layout, so a later layout change never touches an event that sells.
CREATE TABLE event_sections (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id bigint NOT NULL,
    section_key character varying(20) NOT NULL,
    name character varying(100) NOT NULL,
    kind character varying(20) NOT NULL,
    -- SEATED: number of seats; STANDING: how many people the area holds (sold by count, no seats).
    capacity integer NOT NULL,
    -- The price category. Null = not on sale yet.
    ticket_type_id bigint,
    x integer NOT NULL,
    y integer NOT NULL,
    width integer NOT NULL,
    height integer NOT NULL,
    sort_order integer NOT NULL,
    CONSTRAINT event_sections_pkey PRIMARY KEY (id),
    CONSTRAINT uq_event_sections_key UNIQUE (event_id, section_key),
    CONSTRAINT event_sections_kind_check CHECK (kind IN ('SEATED', 'STANDING')),
    CONSTRAINT fk_event_sections_event FOREIGN KEY (event_id) REFERENCES events(id),
    CONSTRAINT fk_event_sections_ticket_type FOREIGN KEY (ticket_type_id) REFERENCES ticket_types(id)
);
CREATE INDEX idx_event_sections_ticket_type ON event_sections (ticket_type_id);

CREATE TABLE event_seats (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    event_id bigint NOT NULL,
    section_id bigint NOT NULL,
    row_label character varying(10) NOT NULL,
    seat_number integer NOT NULL,
    -- Seat centre on the map, in the layout's units.
    x integer NOT NULL,
    y integer NOT NULL,
    accessible boolean NOT NULL DEFAULT false,
    -- Taken off sale by the organizer (camera position, house seats, ...).
    blocked boolean NOT NULL DEFAULT false,
    CONSTRAINT event_seats_pkey PRIMARY KEY (id),
    CONSTRAINT uq_event_seats_place UNIQUE (section_id, row_label, seat_number),
    CONSTRAINT fk_event_seats_event FOREIGN KEY (event_id) REFERENCES events(id),
    CONSTRAINT fk_event_seats_section FOREIGN KEY (section_id) REFERENCES event_sections(id) ON DELETE CASCADE
);
CREATE INDEX idx_event_seats_event ON event_seats (event_id);

-- One order item per seat. The labels are a snapshot, so a ticket never changes once issued.
ALTER TABLE order_items ADD COLUMN event_section_id bigint;
ALTER TABLE order_items ADD COLUMN event_seat_id bigint;
ALTER TABLE order_items ADD COLUMN section_name character varying(100);
ALTER TABLE order_items ADD COLUMN row_label character varying(10);
ALTER TABLE order_items ADD COLUMN seat_number integer;
ALTER TABLE order_items ADD CONSTRAINT fk_order_items_event_section
    FOREIGN KEY (event_section_id) REFERENCES event_sections(id);
ALTER TABLE order_items ADD CONSTRAINT fk_order_items_event_seat
    FOREIGN KEY (event_seat_id) REFERENCES event_seats(id);
CREATE INDEX idx_order_items_event_section ON order_items (event_section_id) WHERE event_section_id IS NOT NULL;
CREATE INDEX idx_order_items_event_seat ON order_items (event_seat_id) WHERE event_seat_id IS NOT NULL;

ALTER TABLE tickets ADD COLUMN event_seat_id bigint;
ALTER TABLE tickets ADD COLUMN section_name character varying(100);
ALTER TABLE tickets ADD COLUMN row_label character varying(10);
ALTER TABLE tickets ADD COLUMN seat_number integer;
ALTER TABLE tickets ADD CONSTRAINT fk_tickets_event_seat FOREIGN KEY (event_seat_id) REFERENCES event_seats(id);

-- Last line of defence behind the seat row locks: one admission per seat.
CREATE UNIQUE INDEX uq_tickets_active_seat ON tickets (event_seat_id)
    WHERE event_seat_id IS NOT NULL AND status IN ('VALID', 'USED');
