package kz.edu.biletflow.backend.entities;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.HashSet;
import java.util.Set;

// A promotional campaign and its one promo code (SRS 4.14). A redemption is an order pointing at it.
@Entity
@Table(name = "promo_campaigns", indexes = @Index(name = "idx_promo_campaigns_event", columnList = "event_id"))
@Getter
@Setter
@NoArgsConstructor
public class PromoCampaign {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id")
    private Long id;

    @Column(name = "name", nullable = false)
    private String name;

    // What attendees type. Uppercase, generated by the server.
    @Column(name = "code", nullable = false, unique = true, updatable = false, length = 20)
    private String code;

    // Opaque value inside the Campaign QR link. It carries no price or discount.
    @Column(name = "token", nullable = false, unique = true, updatable = false, length = 64)
    private String token;

    @Enumerated(EnumType.STRING)
    @Column(name = "discount_type", nullable = false, updatable = false)
    private PromoDiscountType discountType;

    // Percent (0-100) or KZT, depending on discountType.
    @Column(name = "discount_value", nullable = false, updatable = false, precision = 12, scale = 2)
    private BigDecimal discountValue;

    @Column(name = "valid_from")
    private LocalDateTime validFrom;

    @Column(name = "valid_until")
    private LocalDateTime validUntil;

    // Null = unlimited.
    @Column(name = "max_redemptions")
    private Integer maxRedemptions;

    @Column(name = "enabled", nullable = false)
    private boolean enabled = true;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "event_id", nullable = false, foreignKey = @ForeignKey(name = "fk_promo_campaigns_event"))
    private Event event;

    // Empty = every ticket type of the event.
    @ManyToMany(fetch = FetchType.LAZY)
    @JoinTable(name = "promo_campaign_ticket_types",
            joinColumns = @JoinColumn(name = "campaign_id"),
            inverseJoinColumns = @JoinColumn(name = "ticket_type_id"))
    private Set<TicketType> ticketTypes = new HashSet<>();
}
